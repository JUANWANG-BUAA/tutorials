#!/usr/bin/env bash
# Deterministic offline table generation; runtime DSP code contains no floating point.
set -euo pipefail
cd "$(dirname "$0")/../.."
python3 - "$@" <<'PY'
import math
import sys
from pathlib import Path

def quantize(value):
    scaled = value * 32768
    integer = math.floor(scaled + 0.5) if scaled >= 0 else math.ceil(scaled - 0.5)
    return min(32767, max(-32768, integer))
rows = ['/* Generated by generate_tables.sh: exp(-2*pi*i*k/64), Q15. */',
        '#ifndef EDGE_TWIDDLE64_H', '#define EDGE_TWIDDLE64_H',
        'static const DspComplex dsp_twiddle[32] = {']
for k in range(32):
    rows.append(f'    {{{quantize(math.cos(2*math.pi*k/64))}, {quantize(-math.sin(2*math.pi*k/64))}}},')
rows += ['};', '#endif', '']
text = '\n'.join(rows)
path = Path('experiments/ch07/twiddle64.h')
if '--check' in sys.argv:
    if not path.is_file() or path.read_text() != text: raise SystemExit('twiddle table mismatch; regenerate')
    print('PASS twiddle64 table is reproducible')
else:
    path.write_text(text)
PY
